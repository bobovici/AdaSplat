"""Public argument adapters. Algorithms live in Trainer, never in batch CLI."""
import argparse
import json
import os
from datetime import datetime
from pathlib import Path
from uuid import uuid4

from .config import ROOT, load_config, resolve_plan


def common_arguments(parser):
    parser.add_argument('--config',help='JSON config; relative paths inside it use its directory')
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--density',type=float,help='Primitives per pixel; cap=round(density*H*W)')
    group.add_argument('--num','--count',dest='count',type=int,help='Explicit primitive cap (2..200000)')
    parser.add_argument('--steps','--total-steps',dest='steps',type=int,help='Total main-step schedule budget')
    parser.add_argument('--initial-ratio',type=float,help='Initial fraction of the primitive cap')
    parser.add_argument('--growth-fraction',type=float,help='Fraction of main steps allowing births')
    parser.add_argument('--save-counts',help='Comma-separated primitive-count snapshot targets, e.g. 30000,50000,70000,100000,150000,200000')
    parser.add_argument('--seed',type=int)
    parser.add_argument('--no-growth',action='store_true',help='Start at the cap and perform fixed-count fitting')
    parser.add_argument('--no-early-stop',action='store_true')
    parser.add_argument('--smoke',action='store_true',help='Bounded 64-primitive / 12-step cropped test profile')
    parser.add_argument('--dry-run',action='store_true',help='Resolve and print the plan without training or creating output')


def cli_config(args,input_path=None,output_path=None):
    updates = {}
    if input_path is not None:
        updates['input'] = str(Path(input_path).expanduser().resolve())
    if output_path is not None:
        updates['output'] = str(Path(output_path).expanduser().resolve())
    if args.density is not None:
        updates['capacity'] = dict(mode='density',density=args.density,count=None)
    elif args.count is not None:
        updates['capacity'] = dict(mode='count',count=args.count,density=None)
    if args.initial_ratio is not None:
        updates.setdefault('capacity',{})['initial_ratio'] = args.initial_ratio
    if args.steps is not None:
        updates['total_steps'] = args.steps
    if args.seed is not None:
        updates['seed'] = args.seed
    if args.growth_fraction is not None:
        updates.setdefault('growth',{})['fraction'] = args.growth_fraction
    if args.save_counts is not None:
        updates['snapshots'] = dict(counts=[int(v.strip()) for v in args.save_counts.split(',')])
    if args.no_growth:
        updates.setdefault('growth',{})['enabled'] = False
    if args.no_early_stop:
        updates['early_stop'] = dict(enabled=False)
    return load_config(args.config,updates,smoke=args.smoke)


def default_output(prefix):
    return ROOT/'runs'/('{0}_{1}_{2}'.format(prefix,datetime.now().strftime('%Y%m%d_%H%M%S'),uuid4().hex[:6]))


def single_main(argv=None):
    parser = argparse.ArgumentParser(description='Fit one image with a density/count budget and two-stage dynamic allocation.')
    parser.add_argument('--input',help='Input image; RGB conversion preserves native orientation')
    parser.add_argument('--output',help='A new output directory; never overwrite an existing run')
    parser.add_argument('--gpu',type=int,help='Physical GPU index via CUDA_VISIBLE_DEVICES')
    parser.add_argument('--resume',help='Explicit resume.pt generated by this Trainer')
    parser.add_argument('--stop-after',type=int,help='End this session at a main step while preserving the original total schedule')
    common_arguments(parser)
    args = parser.parse_args(argv)
    try:
        if args.gpu is not None and args.gpu<0:
            raise ValueError('gpu must be nonnegative')
        cfg = cli_config(args,args.input,args.output)
        plan = resolve_plan(cfg)
        output = Path(cfg['output']) if cfg['output'] else default_output(Path(plan['input']).stem)
        if args.stop_after is not None and not 1<=args.stop_after<=cfg['total_steps']:
            raise ValueError('stop-after must be within the total schedule')
        if args.dry_run:
            print(json.dumps(dict(config=cfg,resolved_plan=plan,output=str(output),resume=args.resume),indent=2,ensure_ascii=False))
            return 0
        if args.gpu is not None:
            os.environ['CUDA_VISIBLE_DEVICES'] = str(args.gpu)
        # Delay torch/CUDA imports until GPU visibility has been selected.
        from .trainer import Trainer
        trainer = Trainer(cfg,output,resume=args.resume)
        trainer.fit(until_step=args.stop_after)
        print(json.dumps(dict(output=str(output),progress=str(output/'progress.json')),ensure_ascii=False))
        return 0
    except (ValueError,FileNotFoundError,FileExistsError) as error:
        parser.error(str(error))


def batch_main(argv=None):
    parser = argparse.ArgumentParser(description='Enumerate images and schedule the same single-image Trainer on GPU workers.')
    parser.add_argument('--input-dir',required=True)
    parser.add_argument('--output',help='A new batch output directory')
    parser.add_argument('--gpus',default='0,1',help='Comma-separated physical GPU indices (default: 0,1)')
    parser.add_argument('--jobs-per-gpu',type=int,default=2,help='Concurrent image workers per GPU (default: 2)')
    parser.add_argument('--expected-images',type=int,help='Require this image count before launching any worker')
    parser.add_argument('--recursive',action='store_true')
    parser.add_argument('--pattern',action='append',help='Optional glob filter; can be repeated')
    parser.add_argument('--retries',type=int,default=1,help='Maximum additional attempts per failed image')
    common_arguments(parser)
    args = parser.parse_args(argv)
    try:
        cfg = cli_config(args)
        root = Path(args.input_dir).expanduser().resolve(strict=True)
        if not root.is_dir():
            raise ValueError('input-dir must be a directory')
        gpus = [int(v.strip()) for v in args.gpus.split(',')]
        if not gpus or len(set(gpus))!=len(gpus) or min(gpus)<0:
            raise ValueError('gpus must contain unique nonnegative indices')
        if args.jobs_per_gpu<1:
            raise ValueError('jobs-per-gpu must be at least 1')
        if args.retries<0:
            raise ValueError('retries must be nonnegative')
        from .batch import enumerate_images, run_batch
        images = enumerate_images(root,args.recursive,args.pattern)
        if not images:
            raise ValueError('No supported images matched the input directory')
        if args.expected_images is not None and len(images)!=args.expected_images:
            raise ValueError('Expected {0} images, found {1}; check the dataset directory'.format(args.expected_images,len(images)))
        output = Path(args.output).expanduser().resolve() if args.output else default_output('batch')
        if args.dry_run:
            rows = []
            for image in images:
                try:
                    rows.append(dict(input=str(image),plan=resolve_plan(cfg,image)))
                except Exception as error:
                    rows.append(dict(input=str(image),error=str(error)))
            print(json.dumps(dict(images=rows,gpus=gpus,jobs_per_gpu=args.jobs_per_gpu,
                max_parallel_jobs=len(gpus)*args.jobs_per_gpu,output=str(output)),ensure_ascii=False,indent=2))
            return 1 if any('error' in r for r in rows) else 0
        return run_batch(images,root,cfg,output,gpus,args.retries,jobs_per_gpu=args.jobs_per_gpu)
    except (ValueError,FileNotFoundError,FileExistsError) as error:
        parser.error(str(error))
